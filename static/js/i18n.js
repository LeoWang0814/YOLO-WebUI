  const isChinese = () => root.dataset.language === "zh";
  const translate = (value) => {
    if (!isChinese() || typeof value !== "string") return value;
    if (zh[value]) return zh[value];
    const progress = value.match(/^(\d+)% · (.*)$/);
    if (progress) return `${progress[1]}% · ${translate(progress[2])}`;
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(value)) return value.replace(pattern, replacement);
    }
    return value;
  };

  const shouldSkip = (node) => node.parentElement?.closest("script, style, code, pre, [data-i18n-skip], [data-plot]")
    && !node.parentElement?.closest("[data-i18n]");

  // Always retain the canonical English source for client-created content.
  // Capturing already-translated text as the source makes switching back to
  // English impossible (upload status and documentation search used to do this).
  const setText = (element, source) => {
    if (!element) return;
    const value = String(source ?? "");
    const rendered = translate(value);
    element.textContent = rendered;
    if (element.firstChild) originalText.set(element.firstChild, { source: value, rendered });
  };

  const setAttribute = (element, name, source) => {
    if (!element) return;
    const value = String(source ?? "");
    const rendered = translate(value);
    const saved = originalAttributes.get(element) || {};
    saved[name] = { source: value, rendered };
    originalAttributes.set(element, saved);
    element.setAttribute(name, rendered);
  };

  const translateText = (scope) => {
    const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      if (shouldSkip(node)) return;
      const saved = originalText.get(node);
      const original = saved && saved.rendered === node.nodeValue ? saved.source : node.nodeValue;
      const value = original.trim().replace(/\s+/g, " ");
      if (!value) return;
      const rendered = original.replace(/\S[\s\S]*\S|\S/, () => translate(value));
      originalText.set(node, { source: original, rendered });
      if (node.nodeValue !== rendered) node.nodeValue = rendered;
    });
  };

  const translateAttributes = (scope) => {
    const descendants = scope.querySelectorAll ? [...scope.querySelectorAll("*")] : [];
    const elements = [scope, ...descendants];
    elements.forEach((element) => {
      if (!(element instanceof Element) || element.closest("[data-i18n-skip]") || element.parentElement?.closest("[data-plot]")) return;
      const saved = originalAttributes.get(element) || {};
      textAttributes.forEach((attribute) => {
        if (!element.hasAttribute(attribute)) return;
        const current = element.getAttribute(attribute);
        const previous = saved[attribute];
        const source = previous && previous.rendered === current ? previous.source : current;
        const rendered = translate(source);
        saved[attribute] = { source, rendered };
        if (current !== rendered) element.setAttribute(attribute, rendered);
      });
      originalAttributes.set(element, saved);
    });
  };

  const updateToggle = () => {
    const toggle = document.querySelector("[data-language-toggle]");
    if (!toggle) return;
    const label = isChinese() ? "Switch to English" : "Switch to Chinese";
    setAttribute(toggle, "aria-label", label);
    setAttribute(toggle, "title", label);
    toggle.querySelector("[data-language-zh]")?.classList.toggle("is-active", isChinese());
    toggle.querySelector("[data-language-en]")?.classList.toggle("is-active", !isChinese());
  };

  const apply = (scope = document) => {
    root.lang = isChinese() ? "zh-CN" : "en";
    translateText(scope);
    translateAttributes(scope);
    updateToggle();
  };

  const setLanguage = (language) => {
    root.dataset.language = language;
    localStorage.setItem(preferenceKey, language);
    apply(document);
    document.dispatchEvent(new CustomEvent("workbench:languagechange", { detail: { language } }));
  };

  const initialize = () => {
    apply(document);
    document.querySelectorAll("[data-language-toggle]").forEach((toggle) => {
      if (toggle.dataset.bound) return;
      toggle.dataset.bound = "true";
      toggle.addEventListener("click", () => setLanguage(isChinese() ? "en" : "zh"));
    });
  };

  window.WorkbenchI18n = { apply, initialize, isChinese, setLanguage, setText, setAttribute, t: translate };
